// Generates supabase/seed.sql from the programmatic content migration (src/cms/seed.js).
// Usage: node scripts/cms/generate-seed-sql.mjs
// The output is idempotent (ON CONFLICT DO NOTHING), so it can be run again safely.
import fs from 'node:fs';
import path from 'node:path';
import { SEED } from '../../src/cms/seed.js';

const root = path.resolve(import.meta.dirname, '../..');
const publicDir = path.join(root, 'public');
const outFile = path.join(root, 'supabase/seed.sql');

// Columns declared as text[] in the schema; every other array/object column is jsonb.
// (An empty JS array can't be told apart by its contents, so the type comes from the column.)
const TEXT_ARRAY_COLUMNS = new Set(['projects.tags']);

const literal = (value, textArray = false) => {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'boolean' || typeof value === 'number') return String(value);
  if (textArray) return `array[${value.map((v) => literal(v)).join(', ')}]::text[]`;
  if (typeof value === 'object') return `${literal(JSON.stringify(value))}::jsonb`;
  return `'${String(value).replace(/'/g, "''")}'`;
};

const insert = (table, rows, conflict = 'id') =>
  rows.length
    ? rows
        .map((row) => {
          const columns = Object.keys(row);
          return `insert into public.${table} (${columns.join(', ')}) values (${columns
            .map((c) => literal(row[c], TEXT_ARRAY_COLUMNS.has(`${table}.${c}`)))
            .join(', ')}) on conflict (${conflict}) do nothing;`;
        })
        .join('\n')
    : `-- (no ${table} rows)`;

// --- Media library entries for the static assets the content already uses ----------------------
function imageSize(file) {
  const b = fs.readFileSync(file);
  if (b.toString('ascii', 1, 4) === 'PNG') return [b.readUInt32BE(16), b.readUInt32BE(20)];
  if (b.toString('ascii', 0, 4) === 'RIFF' && b.toString('ascii', 8, 12) === 'WEBP') {
    const chunk = b.toString('ascii', 12, 16);
    if (chunk === 'VP8X') return [1 + b.readUIntLE(24, 3), 1 + b.readUIntLE(27, 3)];
    if (chunk === 'VP8L') {
      const bits = b.readUInt32LE(21);
      return [1 + (bits & 0x3fff), 1 + ((bits >> 14) & 0x3fff)];
    }
    if (chunk === 'VP8 ') return [b.readUInt16LE(26) & 0x3fff, b.readUInt16LE(28) & 0x3fff];
  }
  if (b[0] === 0xff && b[1] === 0xd8) {
    let i = 2;
    while (i < b.length) {
      if (b[i] !== 0xff) { i++; continue; }
      const marker = b[i + 1];
      const length = b.readUInt16BE(i + 2);
      if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker))
        return [b.readUInt16BE(i + 7), b.readUInt16BE(i + 5)];
      i += 2 + length;
    }
  }
  return [null, null];
}

const MIME = { webp: 'image/webp', jpg: 'image/jpeg', jpeg: 'image/jpeg', png: 'image/png', mp4: 'video/mp4', pdf: 'application/pdf' };
const referenced = new Set();
(function collect(value) {
  if (typeof value === 'string' && /^assets\/.+\.[a-z0-9]+$/i.test(value)) referenced.add(value);
  else if (value && typeof value === 'object') Object.values(value).forEach(collect);
})(SEED);
referenced.add('assets/5chicks-portfolio.pdf');

const media = [...referenced].sort().flatMap((url) => {
  const file = path.join(publicDir, url);
  if (!fs.existsSync(file)) {
    console.warn('missing static asset, skipped:', url);
    return [];
  }
  const ext = path.extname(url).slice(1).toLowerCase();
  const kind = MIME[ext]?.startsWith('image/') ? 'image' : MIME[ext]?.startsWith('video/') ? 'video' : 'document';
  const [width, height] = kind === 'image' ? imageSize(file) : [null, null];
  return [{
    source: 'static',
    path: url,
    url,
    filename: path.basename(url),
    mime_type: MIME[ext] || null,
    kind,
    width,
    height,
    size_bytes: fs.statSync(file).size
  }];
});

// --- Assemble --------------------------------------------------------------------------------
const { settings, pages, sections, services, sliders, clients, projects } = SEED;
const serviceRows = services.map(({ items, ...row }) => row);
const itemRows = services.flatMap((s) => s.items);
const sliderRows = sliders.map(({ slides, ...row }) => row);
const slideRows = sliders.flatMap((s) => s.slides);
const projectRows = projects.map(({ media: m, ...row }) => row);
const projectMediaRows = projects.flatMap((p) => p.media || []);

const sql = `-- 5CHICKS CMS — initial content
-- GENERATED by scripts/cms/generate-seed-sql.mjs from the existing website content. Do not edit by hand.
-- Idempotent: rows that already exist are left untouched.

begin;

${insert('site_settings', [settings])}

${insert('pages', pages)}

${insert('page_sections', sections)}

${insert('services', serviceRows)}

${insert('service_items', itemRows)}

${insert('sliders', sliderRows)}

${insert('slides', slideRows)}

${insert('clients', clients)}

${insert('projects', projectRows)}

${insert('project_media', projectMediaRows)}

${insert('media', media, 'source, path')}

commit;
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, sql);
console.log(
  `supabase/seed.sql: ${pages.length} pages, ${sections.length} sections, ${serviceRows.length} services (${itemRows.length} items), ` +
    `${sliderRows.length} sliders (${slideRows.length} slides), ${clients.length} clients, ${projectRows.length} projects, ${media.length} media entries`
);
